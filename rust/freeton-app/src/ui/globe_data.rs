fn point_in_polygon(lat: f32, lon: f32, poly: &[(f32, f32)]) -> bool {
    let mut inside = false;
    let n = poly.len();
    if n < 3 {
        return false;
    }
    let mut j = n - 1;
    for i in 0..n {
        let (yi, xi) = poly[i];
        let (yj, xj) = poly[j];
        let intersects = ((yi > lat) != (yj > lat))
            && (lon < (xj - xi) * (lat - yi) / (yj - yi) + xi);
        if intersects {
            inside = !inside;
        }
        j = i;
    }
    inside
}

pub fn is_land(lat_deg: f32, lon_deg: f32) -> bool {
    if !lat_deg.is_finite() || !lon_deg.is_finite() {
        return false;
    }
    if point_in_polygon(lat_deg, lon_deg, NORTH_AMERICA)
        || point_in_polygon(lat_deg, lon_deg, GREENLAND)
        || point_in_polygon(lat_deg, lon_deg, CUBA)
        || point_in_polygon(lat_deg, lon_deg, SOUTH_AMERICA)
        || point_in_polygon(lat_deg, lon_deg, EURASIA_AFRICA)
        || point_in_polygon(lat_deg, lon_deg, ICELAND)
        || point_in_polygon(lat_deg, lon_deg, MADAGASCAR)
    {
        return true;
    }
    if UK_IRELAND
        .iter()
        .any(|poly| point_in_polygon(lat_deg, lon_deg, poly))
    {
        return true;
    }
    ISLANDS_ASIA_OCEANIA
        .iter()
        .any(|poly| point_in_polygon(lat_deg, lon_deg, poly))
}

pub fn land_dots() -> &'static [[f32; 3]] {
    static DOTS: OnceLock<Vec<[f32; 3]>> = OnceLock::new();
    DOTS.get_or_init(|| {
        const TOTAL_SAMPLES: usize = 6_200;
        let golden_angle = std::f32::consts::PI * (3.0 - 5.0_f32.sqrt());
        let mut dots = Vec::with_capacity(1_800);

        for i in 0..TOTAL_SAMPLES {
            let y = 1.0 - (2.0 * (i as f32 + 0.5)) / TOTAL_SAMPLES as f32;
            let r = (1.0 - y * y).max(0.0).sqrt();
            let theta = golden_angle * i as f32;
            let x = theta.cos() * r;
            let z = theta.sin() * r;

            let lat_deg = y.clamp(-1.0, 1.0).asin().to_degrees();
            let lon_deg = x.atan2(z).to_degrees();
            if is_land(lat_deg, lon_deg) {
                dots.push([x, y, z]);
            }
        }
        dots
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_is_land_recognizes_major_landmasses_and_oceans() {
        let land_cities = [
            ("Tokyo", 35.68, 139.65),
            ("Singapore", 1.35, 103.82),
            ("Hanoi", 21.03, 105.85),
            ("Amsterdam", 52.37, 4.90),
            ("London", 51.50, -0.12),
            ("New York", 40.71, -74.00),
            ("Sao Paulo", -23.55, -46.63),
            ("Cairo", 30.04, 31.24),
            ("Sydney", -33.87, 151.21),
        ];
        for (name, lat, lon) in land_cities {
            assert!(is_land(lat, lon), "{name} ({lat}, {lon}) should be on land");
        }

        let oceans = [
            ("Pacific", 0.0, -140.0),
            ("Atlantic", 30.0, -40.0),
            ("Indian", -20.0, 80.0),
        ];
        for (name, lat, lon) in oceans {
            assert!(!is_land(lat, lon), "{name} ({lat}, {lon}) should be ocean");
        }
    }

    #[test]
    fn test_land_dots_count_and_unit_length() {
        let dots = land_dots();
        assert!(
            (1350..=1950).contains(&dots.len()),
            "expected ~1400-1900 land dots, got {}",
            dots.len()
        );
        for d in dots {
            assert!(d.iter().all(|v| v.is_finite()));
            let len = (d[0] * d[0] + d[1] * d[1] + d[2] * d[2]).sqrt();
            assert!((len - 1.0).abs() < 1e-4, "non-unit dot length: {len}");
        }
    }

    #[test]
    fn test_fallback_country_coords_covers_core_countries() {
        let required = [
            "SG", "JP", "US", "NL", "RO", "PL", "CH", "DE", "FR", "GB", "CA", "NO", "MX", "IS",
            "SE", "ES", "IT", "AU", "BR", "IN", "vn", "AT", "UA",
        ];
        for code in required {
            let (lat, lon) = fallback_country_coords(code)
                .unwrap_or_else(|| panic!("missing fallback for {code}"));
            assert!((-90.0..=90.0).contains(&lat));
            assert!((-180.0..=180.0).contains(&lon));
        }
        assert_eq!(fallback_country_coords("ZZ"), None);
    }
}
