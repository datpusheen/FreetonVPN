pub fn fallback_country_coords(code: &str) -> Option<(f32, f32)> {
    let trimmed = code.trim();
    if trimmed.is_empty() {
        return None;
    }
    FALLBACK_COUNTRY_COORDS
        .iter()
        .find(|(iso, _)| iso.eq_ignore_ascii_case(trimmed))
        .map(|(_, coords)| *coords)
}

